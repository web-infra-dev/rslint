func invalidCase(filename, code, output string, line, column, endLine, endColumn int) rule_tester.InvalidTestCase {
	test := rule_tester.InvalidTestCase{
		Code:     code,
		FileName: filename,
		Errors: []rule_tester.InvalidTestCaseError{{
			MessageId: "prefer-boolean-return",
			Message:   "Return the boolean expression directly.",
			Line:      line, Column: column,
			EndLine: endLine, EndColumn: endColumn,
		}},
	}
	if output != "" {
		test.Output = []string{output}
	}
	return test
}
