func invalidCase(code, filename, output string, ranges ...[4]int) rule_tester.InvalidTestCase {
	testCase := rule_tester.InvalidTestCase{Code: code, FileName: filename}
	if output != "" {
		testCase.Output = []string{output}
	}
	for _, span := range ranges {
		testCase.Errors = append(testCase.Errors, rule_tester.InvalidTestCaseError{
			MessageId: "no-selector-as-dom-name",
			Message:   "Do not use selector syntax in DOM names.",
			Line:      span[0], Column: span[1], EndLine: span[2], EndColumn: span[3],
		})
	}
	return testCase
}
