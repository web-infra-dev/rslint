func TestDynamicImportChunknameRegexLiteralTable(t *testing.T) {
	var valid []rule_tester.ValidTestCase
	var invalid []rule_tester.InvalidTestCase
	for _, row := range regexLiteralRows {
		code := "import(\n  /* webpackChunkName: \"a\", webpackInclude: /" + row.pattern + "/" + row.flags + " */\n  'm',\n)"
		if row.valid {
			valid = append(valid, rule_tester.ValidTestCase{Code: code})
			continue
		}
		invalid = append(invalid, rule_tester.InvalidTestCase{
			Code: code,
			Errors: []rule_tester.InvalidTestCaseError{
				{Message: regexInvalidSyntaxMessage, Line: 1, Column: 1, EndLine: 4, EndColumn: 2},
			},
		})
	}
	rule_tester.RunRuleTester(fixtures.GetRootDir(), "tsconfig.json", t, &dynamic_import_chunkname.DynamicImportChunknameRule, valid, invalid)
}
