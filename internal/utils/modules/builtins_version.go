// IsNodeBuiltinAtVersion checks exact builtin specifiers against a Node version.
// Unlike IsNodeBuiltin, it accounts for historical additions and removals.
// Version selection and node: prefix policy belong to the caller.
func IsNodeBuiltinAtVersion(specifier string, version semver.Version) bool {
	supported, ok := nodeBuiltinVersions()[specifier]
	return ok && supported.Test(&version)
}

