// IsDefaultTypeScriptTypeGlobal reports whether name is a type-capable
// implicit variable in typescript-eslint's default TypeScript scope.
func IsDefaultTypeScriptTypeGlobal(name string) bool {
	_, found := slices.BinarySearch(defaultTypeScriptTypeGlobals[:], name)
	return found
}
