const message =
  '`new Array()` is unclear in intent; use an array literal or `Array.from()`.';

function invalid(
  code: string,
  filename: string,
  line: number,
  column: number,
  endLine: number,
  endColumn: number,
  output: string | null,
  suggestion: string | null,
): InvalidTestCase {
  return {
    code,
    filename,
    output,
    errors: [
      {
        messageId: 'error',
        message,
        line,
        column,
        endLine,
        endColumn,
        suggestions:
          suggestion === null
            ? []
            : [
                {
                  messageId: 'spread',
                  desc: 'Spread the argument.',
                  output: suggestion,
                },
              ],
      },
    ],
  };
}

