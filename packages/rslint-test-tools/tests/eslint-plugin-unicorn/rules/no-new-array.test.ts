new RuleTester().run('no-new-array', null as never, cases);

// The suite wrapper checks messages; verify ranges and applied edits through IPC too.
test('upstream diagnostic ranges, fixes, and suggestions', async () => {
  for (const item of cases.invalid) {
    const filename = path.resolve(
      import.meta.dirname,
      '../src',
      item.filename!,
    );
    const { diagnostics } = await lint({
      config: [
        { plugins: ['unicorn'], rules: { 'unicorn/no-new-array': 'error' } },
      ],
      configDirectory: process.cwd(),
      workingDirectory: process.cwd(),
      fileContents: { [filename]: item.code },
    });
    expect(diagnostics, item.code).toHaveLength(1);
    const diagnostic = diagnostics[0];
    const expected = (
      item.errors as Exclude<InvalidTestCase['errors'], number>
    )[0];
    if (typeof expected === 'string')
      throw new Error('Expected structured diagnostic');
    expect(diagnostic, item.code).toMatchObject({
      ruleName: 'unicorn/no-new-array',
      messageId: 'error',
      message,
      range: {
        start: { line: expected.line, column: expected.column },
        end: { line: expected.endLine, column: expected.endColumn },
      },
    });
    expect(applyEdits(item.code, diagnostic.fixes), item.code).toBe(
      item.output,
    );
    expect(
      (diagnostic.suggestions ?? []).map((suggestion) => ({
        messageId: suggestion.messageId,
        desc: suggestion.message,
        output: applyEdits(item.code, suggestion.fixes),
      })),
      item.code,
    ).toEqual(expected.suggestions);
  }
});

function applyEdits(
  code: string,
  fixes?: { startPos: number; endPos: number; text: string }[],
): string | null {
  if (!fixes?.length) return null;
  for (const fix of [...fixes].sort((a, b) => b.startPos - a.startPos)) {
    code = code.slice(0, fix.startPos) + fix.text + code.slice(fix.endPos);
  }
  return code;
}
