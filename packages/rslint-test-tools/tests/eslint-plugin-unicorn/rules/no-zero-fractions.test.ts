interface UpstreamCase {
  code: string;
  filename?: string;
  options?: unknown[];
}
function normalizeCase(value: string | UpstreamCase): UpstreamCase {
  return typeof value === 'string'
    ? { code: value, filename: 'src/virtual.js' }
    : { filename: 'src/virtual.js', ...value };
}

