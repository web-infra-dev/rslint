import { RuleTester, type TestCase } from '@rslint/rule-tester';

function invalid(
  code: string,
  replacement: 'trimStart' | 'trimEnd',
  line: number,
  column: number,
  filename = 'file.js',
): TestCase {
  const method = replacement === 'trimStart' ? 'startsWith' : 'endsWith';
  return {
    code,
    filename,
    output: code.replace('.trim', `.${replacement}`),
    errors: [
      {
        messageId: 'no-unnecessary-string-trim',
        message: `Prefer \`String#${replacement}()\` before \`String#${method}()\`.`,
        line,
        column,
        endLine: line,
        endColumn: column + 4,
      },
    ],
  };
}

