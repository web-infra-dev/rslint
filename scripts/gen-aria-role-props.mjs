// Regenerate with: node scripts/gen-aria-role-props.mjs /path/to/aria-query-v5.3.2
// The path must be an installed aria-query 5.3.2 package (for example
// `npm install aria-query@5.3.2` in an empty directory, then pass
// `<dir>/node_modules/aria-query`).
import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { execFileSync } from 'node:child_process';

const upstream = resolve(process.argv[2] ?? '');
const pkg = JSON.parse(
  await readFile(resolve(upstream, 'package.json'), 'utf8'),
);
if (pkg.name !== 'aria-query' || pkg.version !== '5.3.2') {
  throw new Error('Expected an installed aria-query 5.3.2 package');
}
const { default: aq } = await import(
  pathToFileURL(resolve(upstream, 'lib/index.js')).href
);
const roles = aq.roles;

// Byte-wise order, so Go's binary search over the arrays agrees with it.
const byteOrder = (a, b) => (a < b ? -1 : a > b ? 1 : 0);
const roleNames = [...roles.keys()].sort(byteOrder);
const propNames = [
  ...new Set([...roles.values()].flatMap((role) => Object.keys(role.props))),
].sort(byteOrder);
if (propNames.length > 64) {
  throw new Error(`${propNames.length} ARIA properties do not fit in uint64`);
}
const bit = new Map(propNames.map((name, index) => [name, index]));
const masks = roleNames.map((name) =>
  Object.keys(roles.get(name).props).reduce(
    (mask, prop) => mask | (1n << BigInt(bit.get(prop))),
    0n,
  ),
);

const quote = JSON.stringify;
let output = `// Code generated by scripts/gen-aria-role-props.mjs from aria-query v5.3.2; DO NOT EDIT.
// https://github.com/A11yance/aria-query/tree/v5.3.2/src/etc/roles
package jsxa11yutil

// ariaRolePropNames lists every ARIA property that some role supports; the
// index of a name is its bit position in ariaRoleMasks.
var ariaRolePropNames = [...]string{
${propNames.map((name) => `\t${quote(name)},\n`).join('')}}

// ariaRoleNames lists every role in aria-query's rolesMap, including the
// abstract, DPUB and Graphics roles.
var ariaRoleNames = [...]string{
${roleNames.map((name) => `\t${quote(name)},\n`).join('')}}

// ariaRoleMasks[i] is the set of properties supported by ariaRoleNames[i].
var ariaRoleMasks = [...]uint64{
${masks.map((mask) => `\t0x${mask.toString(16)},\n`).join('')}}
`;
const dataFile = new URL(
  '../internal/plugins/jsx_a11y/jsxa11yutil/role_props_generated.go',
  import.meta.url,
);
await writeFile(dataFile, output);
execFileSync('gofmt', ['-w', dataFile.pathname]);
