#!/usr/bin/env python3
"""Extract the pinned JavaScript AST decoder without compiler or RPC clients.

Generation reads committed Git objects; --verify checks only the checked-in
files and manifest, and requires neither the upstream checkout nor Node.
"""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path, PurePosixPath
import re
import subprocess

PIN = "1f70213d4922b434345f639b441681e470c7cfc1"
UPSTREAM = "https://github.com/microsoft/TypeScript"
PREFIX = "packages/typescript/src/"
OUTPUT = Path("packages/rslint-api/src/ast-compat")
MANIFEST = "UPSTREAM.json"
ROOTS = ("api/node/node.ts", "ast/index.ts")
IMPORTS = re.compile(r'''\b(?:from\s*|import\s*)["']([^"']+)["']''')
NOTICE = """# JavaScript AST compatibility layer

This directory is generated by `scripts/tsrs/extract-js-ast.py` from Microsoft
TypeScript commit `1f70213d4922b434345f639b441681e470c7cfc1`. The Apache-2.0
license and upstream notices are preserved beside this file. `UPSTREAM.json`
records the source and output hashes for each file.

It contains AST data, numeric enums, a binary AST decoder, and lexical and
traversal helpers. It contains no parser, binder, type checker, project loader,
compiler process launcher, or RPC client. The public exports remain
`RemoteSourceFile`, `SyntaxKind`, and the `Node` type.

The upstream generated `isX.Handle` overloads and assignments are omitted:
rslint does not export those helpers, and their type-only dependencies would
otherwise pull the unrelated synchronous and asynchronous compiler clients
into declaration generation. Ordinary node guards remain unchanged.

Normal package builds read this checked-in directory and do not require the
upstream checkout. To reproduce it, initialize the pinned reference checkout
and run `python3 scripts/tsrs/extract-js-ast.py`. Use `--check` to compare with
that source, or `--verify` to verify checked-in hashes without the checkout.
Do not edit the extracted sources directly.
"""


def digest(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def git(source: Path, *args: str) -> bytes:
    return subprocess.run(
        ["git", "-C", str(source), *args], check=True, capture_output=True
    ).stdout


def remove_handles(data: bytes) -> bytes:
    text = data.decode("utf-8").replace("\r\n", "\n")
    text, imports = re.subn(
        r'^import type \{ NodeHandle as (?:Async|Sync)NodeHandle \} from "../api/(?:async|sync)/api.ts";\n',
        "", text, flags=re.M,
    )
    text, aliases = re.subn(r'^type (?:NodeHandleLike|SpecializeNodeHandle)<[^\n]+\n', "", text, flags=re.M)
    text, namespaces = re.subn(
        r'\nexport declare namespace (\w+) \{\n    function Handle<[^\n]+\n\}\n',
        "", text,
    )
    text, assignments = re.subn(r'^\w+\.Handle = \w+ as any;\n', "", text, flags=re.M)
    if imports != 2 or aliases != 2 or namespaces == 0 or assignments != namespaces:
        raise RuntimeError("Pinned node-handle adaptation no longer matches its source")
    if re.search(r'NodeHandle|\.Handle\s*=|namespace \w+', text):
        raise RuntimeError("Unexpected compiler-client type dependency remains in node guards")
    return text.encode()


def references(path: str, data: bytes) -> list[str]:
    result = []
    for name in IMPORTS.findall(data.decode("utf-8")):
        if name.startswith("#enums/"):
            leaf = name.removeprefix("#enums/")
            result.extend((f"enums/{leaf}.ts", f"enums/{leaf}.enum.ts"))
        elif name.startswith("."):
            parts = list(PurePosixPath(path).parent.parts)
            for part in PurePosixPath(name).parts:
                if part == "..":
                    if not parts:
                        raise RuntimeError(f"Import escapes extracted tree: {path}: {name}")
                    parts.pop()
                elif part != ".":
                    parts.append(part)
            result.append("/".join(parts))
        elif name != "node:buffer":
            raise RuntimeError(f"Unexpected external dependency: {path}: {name}")
    return result


def expected_tree(source: Path) -> dict[str, bytes]:
    if git(source, "rev-parse", f"{PIN}^{{commit}}").decode().strip() != PIN:
        raise RuntimeError("Pinned compiler commit is unavailable")
    pending = list(ROOTS)
    files: dict[str, bytes] = {}
    records = []
    while pending:
        name = pending.pop()
        if name in files:
            continue
        # This allowlist excludes both client transports and compiler APIs even
        # when a future import accidentally reaches them.
        allowed = (name.startswith("ast/") or name.startswith("enums/") or
                   name.startswith("api/node/") or name in ("api/timing.ts", "internal/utils.ts"))
        if not allowed:
            raise RuntimeError(f"Unexpected compiler/client dependency: {name}")
        original = git(source, "show", f"{PIN}:{PREFIX}{name}")
        data = remove_handles(original) if name == "ast/is.generated.ts" else original
        files[name] = data
        records.append({"path": name, "source": PREFIX + name,
                        "sourceSha256": digest(original), "sha256": digest(data)})
        pending.extend(references(name, data))
    if len(files) != 55:
        raise RuntimeError(f"Pinned source closure changed: expected 55 files, got {len(files)}")
    for name, upstream in (("LICENSE.typescript", "LICENSE.txt"), ("NOTICE.typescript", "NOTICE.txt")):
        data = git(source, "show", f"{PIN}:{upstream}")
        files[name] = data
        records.append({"path": name, "source": upstream,
                        "sourceSha256": digest(data), "sha256": digest(data)})
    package = {
        "private": True, "type": "module", "license": "Apache-2.0",
        "imports": {"#enums/*": {"types": "./enums/*.enum.ts", "default": "./enums/*.ts"}},
    }
    for name, data in (("package.json", (json.dumps(package, indent=2) + "\n").encode()),
                       ("NOTICE.md", NOTICE.encode())):
        files[name] = data
        records.append({"path": name, "source": None, "sha256": digest(data)})
    manifest = {
        "version": 1, "repository": UPSTREAM, "commit": PIN,
        "roots": list(ROOTS),
        "transformations": ["Remove unexported node-handle overloads and assignments from ast/is.generated.ts"],
        "publicExports": ["RemoteSourceFile", "SyntaxKind", "type Node"],
        "files": sorted(records, key=lambda row: row["path"]),
    }
    files[MANIFEST] = (json.dumps(manifest, indent=2) + "\n").encode()
    return files


def checked_path(output: Path, name: str) -> Path:
    path = PurePosixPath(name)
    if path.is_absolute() or ".." in path.parts or str(path) != name:
        raise RuntimeError(f"Invalid extracted path: {name!r}")
    result = output / name
    if result.is_symlink():
        raise RuntimeError(f"Extracted source must not be a symlink: {name}")
    return result


def verify(output: Path) -> dict:
    data = (output / MANIFEST).read_bytes()
    manifest = json.loads(data)
    if manifest.get("version") != 1 or manifest.get("commit") != PIN or manifest.get("repository") != UPSTREAM:
        raise RuntimeError("Unexpected JavaScript AST provenance")
    names = set()
    for row in manifest["files"]:
        name = row["path"]
        if name in names:
            raise RuntimeError(f"Duplicate extracted source: {name}")
        names.add(name)
        if digest(checked_path(output, name).read_bytes()) != row["sha256"]:
            raise RuntimeError(f"Modified JavaScript AST source: {name}")
    actual = {p.relative_to(output).as_posix() for p in output.rglob("*") if p.is_file()}
    if actual != names | {MANIFEST}:
        raise RuntimeError(f"Unexpected extracted files: {sorted(actual ^ (names | {MANIFEST}))}")
    return {"repository": UPSTREAM, "commit": PIN, "manifestSha256": digest(data), "fileCount": len(names)}


def main() -> None:
    root = Path(__file__).resolve().parents[2]
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=root / "typescript-go")
    parser.add_argument("--output", type=Path, default=root / OUTPUT)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true", help="Compare against the pinned upstream Git objects")
    mode.add_argument("--verify", action="store_true", help="Verify checked-in hashes without the upstream checkout")
    args = parser.parse_args()
    if args.verify:
        print(json.dumps(verify(args.output), sort_keys=True))
        return
    expected = expected_tree(args.source)
    manifest_path = args.output / MANIFEST
    old = json.loads(manifest_path.read_text()) if manifest_path.exists() else {"files": []}
    owned = {row["path"]: row["sha256"] for row in old["files"]}
    if set(owned) - set(expected):
        raise RuntimeError("Previous extraction has extra files; review before removing them")
    changed = []
    for name, data in expected.items():
        destination = checked_path(args.output, name)
        actual = destination.read_bytes() if destination.exists() else None
        if actual == data:
            continue
        changed.append(name)
        if args.check:
            continue
        if actual is not None and name != MANIFEST and owned.get(name) != digest(actual):
            raise RuntimeError(f"Refusing to overwrite modified or unowned source: {name}")
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_bytes(data)
    if args.check and changed:
        raise SystemExit("JavaScript AST extraction differs: " + ", ".join(changed))
    print(json.dumps(verify(args.output), sort_keys=True))


if __name__ == "__main__":
    main()
