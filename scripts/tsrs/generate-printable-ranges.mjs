// Reproduce the frozen Go compiler's printable tables using only Node.js.
// Usage: node scripts/tsrs/generate-printable-ranges.mjs [--check] [--source isprint.go]
// The optional source is read-only; otherwise the pinned public release is fetched.
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const args = process.argv.slice(2);
const check = args.includes('--check');
const sourceIndex = args.indexOf('--source');
assert(
  args.every(
    (arg, index) =>
      arg === '--check' ||
      arg === '--source' ||
      (sourceIndex >= 0 && index === sourceIndex + 1),
  ),
  'unexpected argument',
);
assert(
  sourceIndex < 0 || typeof args[sourceIndex + 1] === 'string',
  '--source needs a filename',
);
const sourceUrl =
  'https://raw.githubusercontent.com/golang/go/go1.27.1/src/strconv/isprint.go';
const sourceSha =
  'e6f4b35fbf38f9c9c8b251e5d3cf94daa880789cb89825f11f9734ba4a42e9ff';
let source;
if (sourceIndex >= 0) {
  source = await readFile(args[sourceIndex + 1], 'utf8');
} else {
  const response = await fetch(sourceUrl);
  assert(response.ok, `source request returned ${response.status}`);
  source = await response.text();
}
assert.equal(
  createHash('sha256').update(source).digest('hex'),
  sourceSha,
  'source differs from frozen Go 1.27.1 / Unicode 17.0.0',
);
const names = [
  ['isPrint16', 'IS_PRINT_16', 'u16'],
  ['isNotPrint16', 'IS_NOT_PRINT_16', 'u16'],
  ['isPrint32', 'IS_PRINT_32', 'u32'],
  ['isNotPrint32', 'IS_NOT_PRINT_32', 'u16'],
];
let generated =
  '// BEGIN GENERATED PRINTABLE RANGES\n// Generated by scripts/tsrs/generate-printable-ranges.mjs; do not edit.\n';
for (const [sourceName, name, type] of names) {
  const match = source.match(
    new RegExp(
      `var ${sourceName} = \\[\\]uint(?:16|32)\\{[^\\n]*\\n([\\s\\S]*?)\\n\\}`,
    ),
  );
  assert(match, `missing ${sourceName}`);
  const values = match[1].match(/0x[0-9a-f]+/g);
  assert(values?.length > 0, `empty ${sourceName}`);
  assert(
    values.every(
      (value, index) =>
        index === 0 || Number(values[index - 1]) <= Number(value),
    ),
    `unsorted ${sourceName}`,
  );
  generated += `#[rustfmt::skip]\nconst ${name}: &[${type}] = &[\n`;
  for (let index = 0; index < values.length; index += 8) {
    generated += `    ${values.slice(index, index + 8).join(', ')},\n`;
  }
  generated += '];\n';
}
generated += '// END GENERATED PRINTABLE RANGES';
const target = fileURLToPath(
  new URL('../../crates/rslint-core/src/rules/go_quote.rs', import.meta.url),
);
const previous = await readFile(target, 'utf8');
const pattern =
  /\/\/ BEGIN GENERATED PRINTABLE RANGES[\s\S]*?\/\/ END GENERATED PRINTABLE RANGES/;
assert(pattern.test(previous), 'generated section missing');
const next = previous.replace(pattern, generated);
if (check)
  assert.equal(next, previous, 'printable ranges require regeneration');
else await writeFile(target, next);
console.log(
  `${check ? 'checked' : 'generated'} Unicode 17.0.0 printable ranges from Go 1.27.1 (${sourceSha})`,
);
