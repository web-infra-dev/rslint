// Regenerate with:
// node scripts/gen-unicorn-name-replacements.mjs /path/to/eslint-plugin-unicorn
import { execFileSync } from 'node:child_process';
import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const upstream = resolve(process.argv[2] ?? '');
const packageJson = JSON.parse(
  await readFile(resolve(upstream, 'package.json'), 'utf8'),
);
if (
  packageJson.name !== 'eslint-plugin-unicorn' ||
  packageJson.version !== '77.0.0'
) {
  throw new Error('Expected an installed eslint-plugin-unicorn 77.0.0 package');
}

const { defaultAllowList, defaultIgnore, defaultReplacements } = await import(
  pathToFileURL(resolve(upstream, 'rules/shared/name-replacements.js')).href
);

const byteOrder = (first, second) =>
  first < second ? -1 : first > second ? 1 : 0;
const pairs = Object.entries(defaultReplacements)
  .sort(([first], [second]) => byteOrder(first, second))
  .flatMap(([name, replacements]) => {
    if (!replacements || typeof replacements !== 'object') {
      throw new Error(`Invalid replacements for ${name}`);
    }
    return Object.entries(replacements)
      .sort(([first], [second]) => byteOrder(first, second))
      .map(([replacement, enabled]) => {
        if (enabled !== true) {
          throw new Error(`Expected ${name} -> ${replacement} to be enabled`);
        }
        return { name, replacement };
      });
  });
const allowList = Object.entries(defaultAllowList).sort(([first], [second]) =>
  byteOrder(first, second),
);
if (allowList.some(([, enabled]) => enabled !== true)) {
  throw new Error('Expected every default allow-list entry to be enabled');
}
if (!defaultIgnore.every((pattern) => typeof pattern === 'string')) {
  throw new Error('Expected every default ignore pattern to be a string');
}
if (
  Object.keys(defaultReplacements).length !== 92 ||
  pairs.length !== 104 ||
  allowList.length !== 12 ||
  defaultIgnore.length !== 6
) {
  throw new Error('Unexpected eslint-plugin-unicorn name-replacements data');
}

const quote = JSON.stringify;
const output = `// Code generated by scripts/gen-unicorn-name-replacements.mjs from eslint-plugin-unicorn v77.0.0; DO NOT EDIT.
// https://github.com/sindresorhus/eslint-plugin-unicorn/blob/v77.0.0/rules/shared/name-replacements.js
// cspell:ignore idents retval vite
package name_replacements

var defaultReplacementPairs = [...]defaultReplacementPair{
${pairs.map(({ name, replacement }) => `\t{${quote(name)}, ${quote(replacement)}},\n`).join('')}
}

var defaultAllowList = map[string]bool{
${allowList.map(([name]) => `\t${quote(name)}: true,\n`).join('')}
}

var defaultIgnore = []string{${defaultIgnore.map(quote).join(', ')}}
`;

const dataFile = new URL(
  '../internal/plugins/unicorn/rules/name_replacements/defaults_generated.go',
  import.meta.url,
);
await writeFile(dataFile, output);
execFileSync('gofmt', ['-w', fileURLToPath(dataFile)]);
