// Regenerate with: node scripts/gen-type-service-enums.mjs
// Pass --check (or set CI=true) to verify without modifying tracked files.
// Also runs automatically before `pnpm --filter @rslint/core dev` and `build:js`.
import { readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const checkOnly = process.argv.includes('--check') || process.env.CI === 'true';

const repoRoot = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  '..',
);
const coreRequire = createRequire(
  path.join(repoRoot, 'packages/rslint/package.json'),
);
const ts = coreRequire('typescript');
const tsPkg = JSON.parse(
  await readFile(coreRequire.resolve('typescript/package.json'), 'utf8'),
);

function forwardEnum(table) {
  const result = {};
  for (const [key, value] of Object.entries(table)) {
    if (typeof value === 'number') {
      result[key] = value;
    }
  }
  return result;
}

function extractCompilerData(typescript) {
  const canHaveJSDoc = Reflect.get(typescript, 'canHaveJSDoc');
  const isJSDocHost =
    typeof canHaveJSDoc === 'function'
      ? (node) => Boolean(Reflect.apply(canHaveJSDoc, typescript, [node]))
      : () => false;
  const jsDocKinds = {};
  for (const [name, kind] of Object.entries(typescript.SyntaxKind)) {
    if (typeof kind === 'number' && isJSDocHost({ kind })) {
      jsDocKinds[name] = true;
    }
  }
  // TypeScript's JS AST initializes jsDoc on ModuleBlock and MissingDeclaration,
  // while EndOfFileToken and SemicolonClassElement carry it only when commented.
  jsDocKinds.ModuleBlock = true;
  jsDocKinds.MissingDeclaration = true;
  delete jsDocKinds.EndOfFileToken;
  delete jsDocKinds.SemicolonClassElement;

  return {
    SyntaxKind: forwardEnum(typescript.SyntaxKind),
    TypeFlags: forwardEnum(typescript.TypeFlags),
    ObjectFlags: forwardEnum(typescript.ObjectFlags),
    NodeFlags: forwardEnum(typescript.NodeFlags),
    JsxEmit: forwardEnum(typescript.JsxEmit),
    ModuleDetectionKind: forwardEnum(typescript.ModuleDetectionKind),
    ScriptTarget: forwardEnum(typescript.ScriptTarget),
    builderEmitFlags: Array.from(
      { length: 8 },
      (_, mask) =>
        (mask & 1 ? typescript.EmitFlags.SingleLine : 0) |
        (mask & 2 ? typescript.EmitFlags.NoIndentation : 0) |
        (mask & 4 ? typescript.EmitFlags.NoAsciiEscaping : 0),
    ),
    jsDocKinds,
  };
}

function formatKey(key) {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(key) ? key : JSON.stringify(key);
}

function formatRecord(record) {
  const lines = Object.entries(record).map(
    ([key, value]) => `    ${formatKey(key)}: ${JSON.stringify(value)},`,
  );
  return `{\n${lines.join('\n')}\n  }`;
}

function formatNumberArray(values) {
  const inline = `[${values.join(', ')}]`;
  if (`  builderEmitFlags: ${inline},`.length <= 80) {
    return inline;
  }
  return `[\n    ${values.join(', ')},\n  ]`;
}

const data = extractCompilerData(ts);

const outputPath = path.join(
  repoRoot,
  'packages/rslint/src/languages/js/type-service-compiler-data.generated.ts',
);

const content = `// Code generated by scripts/gen-type-service-enums.mjs from typescript ${tsPkg.version}; DO NOT EDIT.
// cspell:disable
import type { TypeServiceCompilerData } from './type-service-compiler-data.js';

export const TYPESCRIPT_COMPILER_DATA = {
  SyntaxKind: ${formatRecord(data.SyntaxKind)},
  TypeFlags: ${formatRecord(data.TypeFlags)},
  ObjectFlags: ${formatRecord(data.ObjectFlags)},
  NodeFlags: ${formatRecord(data.NodeFlags)},
  JsxEmit: ${formatRecord(data.JsxEmit)},
  ModuleDetectionKind: ${formatRecord(data.ModuleDetectionKind)},
  ScriptTarget: ${formatRecord(data.ScriptTarget)},
  builderEmitFlags: ${formatNumberArray(data.builderEmitFlags)},
  jsDocKinds: ${formatRecord(data.jsDocKinds)},
} as const satisfies TypeServiceCompilerData;
`;

let existing = '';
try {
  existing = (await readFile(outputPath, 'utf8')).replaceAll('\r\n', '\n');
} catch (error) {
  if (error?.code !== 'ENOENT') throw error;
}

if (existing !== content) {
  if (checkOnly) {
    console.error(
      `[gen-type-service-enums] ${path.relative(repoRoot, outputPath)} is out of date with typescript ${tsPkg.version}. Run \`pnpm --filter @rslint/core gen:enums\` to regenerate.`,
    );
    process.exit(1);
  }
  await writeFile(outputPath, content, 'utf8');
}
